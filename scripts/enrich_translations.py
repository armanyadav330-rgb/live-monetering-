translations_dir = 'src/i18n/translations'

for lang_code in extra_translations:
    filepath = os.path.join(translations_dir, f"{lang_code}.ts")
    if not os.path.exists(filepath):
        print(f"Warning: {filepath} not found!")
        continue
    
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # Extract existing dictionary using regex
    # Match everything between 'const ... = {' or 'export default {' and '};'
    match = re.search(r'export default\s*({[\s\S]*?});?\s*$', content)
    if not match:
        match = re.search(r'const\s+\w+\s*:\s*Record<string,\s*string>\s*=\s*({[\s\S]*?});', content)
    
    # Parse key-values from the file
    current_dict = {}
    lines = content.split('\n')
    for line in lines:
        m = re.match(r"^\s*['\"]([^'\"]+)['\"]\s*:\s*['\"](.*)['\"],?\s*$", line)
        if m:
            key, val = m.group(1), m.group(2)
            # handle escaped quotes
            val = val.replace('\\"', '"').replace("\\'", "'")
            current_dict[key] = val

    # Merge extras
    extras = extra_translations[lang_code]
    for k, v in extras.items():
        current_dict[k] = v

    # Write back clean TypeScript file
    out_lines = [
        f"// Centralized i18n translation dictionary for: {lang_code}",
        "const dictionary: Record<string, string> = {"
    ]
    for k in sorted(current_dict.keys()):
        val = current_dict[k].replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
        out_lines.append(f'  "{k}": "{val}",')
    out_lines.append("};")
    out_lines.append("")
    out_lines.append("export default dictionary;")
    out_lines.append("")

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out_lines))
    print(f"Updated {lang_code}.ts with {len(current_dict)} keys.")

